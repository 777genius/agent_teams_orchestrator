export function getAnthropicConnectionMode(
  env: NodeJS.ProcessEnv = process.env,
): AnthropicConnectionMode {
  const raw = env[AGENT_TEAMS_ANTHROPIC_CONNECTION_MODE_ENV]
    ?.trim()
    .toLowerCase()
  switch (raw) {
    case 'subscription':
    case 'api_key':
    case 'compatible':
      return raw
    default:
      return 'auto'
  }
}

export function hasExplicitAnthropicConnectionMode(
  env: NodeJS.ProcessEnv = process.env,
): boolean {
  return getAnthropicConnectionMode(env) !== 'auto'
}

export function hasAppManagedAnthropicApiKeyHelper(
  env: NodeJS.ProcessEnv = process.env,
): boolean {
  return (
    env[APP_MANAGED_ANTHROPIC_AUTH_MODE_ENV] ===
      APP_MANAGED_ANTHROPIC_AUTH_MODE_API_KEY_HELPER &&
    typeof env[APP_MANAGED_ANTHROPIC_SETTINGS_PATH_ENV] === 'string' &&
    env[APP_MANAGED_ANTHROPIC_SETTINGS_PATH_ENV]!.trim().length > 0
  )
}
